MODULE MOD_POISS_MGBICG
      USE MOD_COMMON, ONLY : M1M,M2M,M3M

!======================= PARAMETERS ==================================
       INTEGER*8, PARAMETER :: M1MD= 2*M1M  ! PARAMETER FOR THE MULTIGRID INDEX
       INTEGER*8, PARAMETER :: M3MD= 2*M3M  ! PARAMETER FOR THE MULTIGRID INDEX
       INTEGER*8, PARAMETER :: MLEV= 20     ! MAXIMUM LEVEL OF MULTIGRID 

       REAL*8    :: AW(M1MD),AE(M1MD),AS(M2M),AN(M2M),AB(M3MD),AF(M3MD)
       INTEGER*8 :: KPM(M3MD),KMM(M3MD)
       INTEGER*8 ::  IIMG(0:MLEV,3),KKMG(0:MLEV,3)               &
                    ,IH1(M1MD),IH2(M1MD),KH1(M3MD),KH2(M3MD)     &
                    ,IL1(M1MD),IL2(M1MD),KL1(M3MD),KL2(M3MD)
       REAL*8    :: FIDW(M1MD),FKDW(M3MD),FIUP(M1MD),FKUP(M3MD)
       REAL*8, DIMENSION (:,:,:), ALLOCATABLE :: GAM,BET

      REAL*8 :: PDX(M1MD),PDY(M2M),PDZ(M3MD),OPENX(M1MD)
END MODULE 
! M1MD,M3MD: PARAMETER FOR THE MULTIGRID INDEX
! MLEV: MAXIMUM LEVEL OF MULTIGRID 
! IIMG, KKMG: START AND END INDEX FOR EACH LEVEL OF THE GRID SYSTEM
! IH1,IH2,KH1,KH2: INDEX OF RESIDEU TO BE RESTRICTION
! IL1,IL2,KL1,KL2: INDEX OF RHS TO BE PROLONGATION
! AW, AE, AS, AN, AB, AF: COEEFICIENT FOR THE ITERATIVE METHOD (AX=b)
! FIDW, FKDW, FIUP, FKUP: COEEFICIENT FOR THE MULTIGRID RESTRICTION AND PROLONGATION
! GAM,BET: COEFICIENT FOR THE SOLVER OF TRIDIGONAL MATRIX
! KPM,KMM: INDEX OF Z DIECTION. IT IS INCLUDED FOR THE Z-DIRECTION PERIODICITY